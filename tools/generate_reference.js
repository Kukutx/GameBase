#!/usr/bin/env node
// Writes the reference pages of the foundation from its code, so they never
// fall behind it:
//
//   node tools/generate_reference.js [--check]
//
//   docs/reference/autoloads.md  every autoload of tiamat/tiamat.json, in
//                                the order a game loads them, with its layer,
//                                script and what its class doc says it does;
//   docs/reference/events.md     the signals of those autoloads: what a
//                                trigger and a quest objective listen to
//                                ("Autoload.signal", GameEvent) and the game's
//                                code connects to;
//   docs/reference/rules.md      the condition and action keys the core and
//                                the modules register with GameRules, with
//                                the usage and meaning their doc comment gives;
//   docs/reference/content.md    the kinds of content the core and the
//                                modules define: each kind's class and what
//                                it is, and the fields its entries set, with
//                                their type, default, range and doc comment.
//
// --check writes nothing and fails when a page differs from what the code
// gives; validation runs it, so a change to the code updates its page in the
// same commit.
const fs = require("node:fs");
const path = require("node:path");
const { fail, main, parseToolArgs, rootPath } = require("./lib/common");
const { readFoundation } = require("./lib/games");
const { typeOfDefault } = require("./new_content");

const REFERENCE_DIR = rootPath("docs", "reference");
const HEADER = "<!-- Generated by node tools/generate_reference.js from the code. Do not edit; run the tool. -->";

function scriptPath(res) {
  return rootPath(...res.slice("res://".length).split("/"));
}

// The `##` lines of a doc comment as text: a paragraph per run of lines,
// joined by a space.
function docText(lines) {
  const paragraphs = [[]];
  for (const line of lines) {
    const text = line.replace(/^##\s?/, "").trim();
    if (text === "") {
      if (paragraphs[paragraphs.length - 1].length > 0) paragraphs.push([]);
    } else {
      paragraphs[paragraphs.length - 1].push(text);
    }
  }
  return paragraphs.filter((paragraph) => paragraph.length > 0).map((paragraph) => paragraph.join(" "));
}

// The first paragraph of the class doc: the `##` lines that follow
// `class_name` and `extends` before anything else.
function classSummary(source) {
  const lines = source.split(/\r?\n/);
  let index = 0;
  while (index < lines.length && /^(class_name|extends|@tool|@icon|\s*$)/.test(lines[index])) index += 1;
  const doc = [];
  while (index < lines.length && lines[index].startsWith("##")) doc.push(lines[index++]);
  return docText(doc)[0] || "";
}

// The signals the script declares, each with its doc comment.
function signalsOf(source) {
  const signals = [];
  let doc = [];
  for (const line of source.split(/\r?\n/)) {
    const match = /^signal\s+(\w+)\s*(\([^)]*\))?/.exec(line);
    if (match) {
      signals.push({ name: match[1], params: match[2] || "()", doc: docText(doc).join(" ") });
      doc = [];
    } else if (line.startsWith("##")) {
      doc.push(line);
    } else {
      doc = [];
    }
  }
  return signals;
}

// The text of the call arguments that start at `start`, split at the commas
// outside brackets and strings.
function callArguments(source, start) {
  const args = [];
  let depth = 0;
  let quote = null;
  let current = "";
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (quote) {
      if (char === quote && source[index - 1] !== "\\") quote = null;
    } else if (char === '"' || char === "'") {
      quote = char;
    } else if ("([{".includes(char)) {
      depth += 1;
    } else if (")]}".includes(char)) {
      if (depth === 0) break;
      depth -= 1;
    } else if (char === "," && depth === 0) {
      args.push(current.trim());
      current = "";
      continue;
    }
    current += char;
  }
  args.push(current.trim());
  return args;
}

function layerOf(file) {
  const match = /^tiamat\/modules\/([^/]+)\//.exec(file);
  return match ? match[1] : "core";
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory() && entry.name !== "test") walk(full, out);
    else if (entry.isFile() && entry.name.endsWith(".gd")) out.push(full);
  }
  return out;
}

// Every key the foundation registers with GameRules, with the usage and the
// meaning its doc comment gives ("## KEY <arg>: what it means").
function ruleKeys() {
  const keys = [];
  for (const full of walk(rootPath("tiamat")).sort()) {
    const file = path.relative(rootPath(), full).split(path.sep).join("/");
    const source = fs.readFileSync(full, "utf8");
    for (const match of source.matchAll(/\bregister_(condition|action)\s*\(/g)) {
      const args = callArguments(source, match.index + match[0].length);
      const key = (/^&"([A-Z][A-Z0-9_]*)"$/.exec(args[0]) || [])[1];
      if (!key) continue;
      const lines = source.split(/\r?\n/);
      const at = lines.findIndex((line) => new RegExp(`^## ${key}\\b`).test(line));
      const doc = [];
      for (let index = at; at >= 0 && index < lines.length && lines[index].startsWith("##"); index += 1) doc.push(lines[index]);
      const text = docText(doc).join(" ");
      const colon = text.indexOf(": ");
      const usage = text ? (colon >= 0 ? text.slice(0, colon) : text) : key;
      const meaning = colon >= 0 ? text.slice(colon + 2) : "";
      keys.push({ kind: match[1], key, layer: layerOf(file), file, usage, meaning, min: Number(args[2]), max: Number(args[3]) });
    }
  }
  return keys.sort((a, b) => a.key.localeCompare(b.key));
}

// The autoloads of the foundation in load order: [name, script, layer].
function autoloads(foundation) {
  const list = [];
  for (const [name, script] of Object.entries(foundation.autoloads.before_modules)) list.push([name, script, "core"]);
  for (const module of Object.keys(foundation.modules).sort()) {
    for (const [name, script] of Object.entries(foundation.modules[module].autoloads || {})) list.push([name, script, module]);
  }
  for (const [name, script] of Object.entries(foundation.autoloads.after_modules)) list.push([name, script, "core"]);
  return list;
}

function cell(text) {
  return String(text).replace(/\|/g, "\\|");
}

function autoloadsPage(foundation) {
  const lines = [
    HEADER,
    "",
    "# Autoloads",
    "",
    "The services the foundation runs as autoloads. A game has the core's and those of the modules its `game.json` lists; `node tools/link.js` writes them into its `project.godot` in this order: the core's first group, the modules' (a module after the modules it requires), the core's second group, then the game's own. A module's autoloads come from `tiamat/tiamat.json`.",
    "",
    "| Autoload | Layer | Script | What it does |",
    "| --- | --- | --- | --- |",
  ];
  for (const [name, script, layer] of autoloads(foundation)) {
    const summary = script.startsWith("res://addons/") ? "From the addon of that name." : classSummary(fs.readFileSync(scriptPath(script), "utf8"));
    lines.push(`| \`${name}\` | ${layer} | \`${script.slice("res://".length)}\` | ${cell(summary)} |`);
  }
  return `${lines.join("\n")}\n`;
}

function eventsPage(foundation) {
  const lines = [
    HEADER,
    "",
    "# Events",
    "",
    'The signals of the foundation\'s autoloads. A trigger or a quest objective names one as its event, `"Autoload.signal"` (`GameEvent`), and its condition reads the signal\'s arguments by name, as do a trigger\'s actions; the game\'s own code connects to them, or listens through a `GameEventListener`. An argument named `<kind>_id`, or ending in `_<kind>_id`, holds an id of that kind of content. Only the module that owns an `<Module>Events` autoload emits its signals.',
    "",
  ];
  for (const [name, script, layer] of autoloads(foundation)) {
    if (script.startsWith("res://addons/")) continue;
    const signals = signalsOf(fs.readFileSync(scriptPath(script), "utf8"));
    if (signals.length === 0) continue;
    lines.push(`## ${name} (${layer})`, "");
    for (const signal of signals) {
      lines.push(`- \`${name}.${signal.name}${signal.params}\`${signal.doc ? `: ${signal.doc}` : ""}`);
    }
    lines.push("");
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

function argumentCount(entry) {
  if (entry.max < 0) return `${entry.min} or more`;
  return entry.min === entry.max ? String(entry.min) : `${entry.min} to ${entry.max}`;
}

function rulesPage() {
  const keys = ruleKeys();
  const lines = [
    HEADER,
    "",
    "# Rule keys",
    "",
    "The condition and action keys the core and the modules register with `GameRules`. Content writes them as text: a condition is keys joined by `,` (all must hold) or `|` (one must), such as `SEASON Spring, HAS_ITEM berry 3`, and an action is one key and its arguments. A game has the core's keys and those of the modules it links; content checks reject a key or an argument count that does not fit.",
    "",
  ];
  for (const [kind, title] of [["condition", "Conditions"], ["action", "Actions"]]) {
    lines.push(`## ${title}`, "", "| Key | Layer | Arguments | Usage | What it means |", "| --- | --- | --- | --- | --- |");
    for (const entry of keys.filter((candidate) => candidate.kind === kind)) {
      lines.push(`| \`${entry.key}\` | ${entry.layer} | ${argumentCount(entry)} | \`${cell(entry.usage)}\` | ${cell(entry.meaning)} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

const KIND_RE = /^const KIND\s*:?=\s*&"([^"]+)"/m;
const CLASS_RE = /^class_name\s+(\w+)/m;
// An exported field on one line: its annotation (`_range`, `_file`, ...) and
// the annotation's arguments, its name, its type and its default.
const FIELD_RE = /^@export(\w*)(?:\(([^)\n]*)\))?\s+var\s+(\w+)\s*(?::\s*([^=\n]+?))?\s*(?::?=\s*(.+))?$/;

const ENGINE_TYPE_RE = /^(Color|Vector[234]i?|Rect2i?|Transform[23]D|Basis|Quaternion|Plane|AABB)$/;

// The enums the script declares: name -> [{ value, number, doc }], in order,
// each value with its doc comment.
function enumsOf(source) {
  const enums = new Map();
  for (const match of source.matchAll(/^enum\s+(\w+)\s*\{([^}]*)\}/gm)) {
    const values = [];
    let next = 0;
    let doc = [];
    for (const line of match[2].split(/\r?\n/)) {
      const text = line.trim();
      if (text.startsWith("##")) {
        doc.push(text);
        continue;
      }
      for (const part of text.replace(/#.*$/, "").split(",")) {
        const value = /^\s*(\w+)\s*(?:=\s*(-?\d+))?\s*$/.exec(part);
        if (!value) continue;
        if (value[2] !== undefined) next = Number(value[2]);
        values.push({ value: value[1], number: next, doc: docText(doc).join(" ") });
        doc = [];
        next += 1;
      }
    }
    enums.set(match[1], values);
  }
  return enums;
}

// The fields the script exports, in order, each with its annotation and its
// arguments, its type as declared, its default and its doc comment.
function fieldsOf(source) {
  const fields = [];
  let doc = [];
  for (const line of source.split(/\r?\n/)) {
    const match = FIELD_RE.exec(line);
    if (match) {
      const [, annotation, args, name, type, initial] = match;
      fields.push({ name, annotation, args: args || "", type: (type || "").trim(), initial: (initial || "").trim(), doc: docText(doc).join(" ") });
      doc = [];
    } else if (line.startsWith("##")) {
      doc.push(line);
    } else {
      doc = [];
    }
  }
  return fields;
}

// The kinds of content the foundation defines, sorted by layer (the core
// first) and kind: each its kind, class, layer, script and source.
function contentKinds() {
  const kinds = [];
  for (const full of walk(rootPath("tiamat"))) {
    const source = fs.readFileSync(full, "utf8");
    const kind = KIND_RE.exec(source);
    const name = CLASS_RE.exec(source);
    if (!kind || !name) continue;
    const file = path.relative(rootPath(), full).split(path.sep).join("/");
    kinds.push({ kind: kind[1], name: name[1], layer: layerOf(file), file, source });
  }
  const rank = (entry) => (entry.layer === "core" ? "" : entry.layer);
  return kinds.sort((a, b) => rank(a).localeCompare(rank(b)) || a.kind.localeCompare(b.kind));
}

function plainNumber(text) {
  const number = Number(text);
  return Number.isFinite(number) ? String(number) : text;
}

// What the editor holds the field to, as the player of a `.tres` reads it:
// "0.1 to 60 s", "a *.tscn file", "a folder", "several lines".
function editorHint(field) {
  const args = field.args ? callArguments(field.args, 0) : [];
  if (field.annotation === "_range" && args.length >= 2) {
    const hints = args.slice(2).filter((arg) => arg.startsWith('"')).map((arg) => arg.slice(1, -1));
    const suffix = (hints.find((hint) => hint.startsWith("suffix:")) || "").slice("suffix:".length);
    const more = hints.includes("or_greater") ? " or more" : "";
    return `${plainNumber(args[0])} to ${plainNumber(args[1])}${suffix ? ` ${suffix}` : ""}${more}`;
  }
  if (field.annotation === "_file") return args.length > 0 ? `a ${args[0].slice(1, -1)} file` : "a file";
  if (field.annotation === "_dir") return "a folder";
  if (field.annotation === "_multiline") return "several lines";
  return "";
}

// The enum values the field's type names, from its own class or another
// (`WorldLocationData.LocationType`), each with its doc comment:
// "TOWN = 0, INTERIOR = 1", "DAMAGE = 0 (takes health), HEAL = 1".
function enumValues(type, own, enumsByClass) {
  for (const match of type.matchAll(/(?:(\w+)\.)?(\w+)/g)) {
    const enums = match[1] ? enumsByClass.get(match[1]) : own;
    const values = enums && enums.get(match[2]);
    if (values) return values.map((entry) => `${entry.value} = ${entry.number}${entry.doc ? ` (${entry.doc.replace(/\.$/, "")})` : ""}`).join(", ");
  }
  return "";
}

function contentPage() {
  const kinds = contentKinds();
  const enumsByClass = new Map(kinds.map((entry) => [entry.name, enumsOf(entry.source)]));
  const lines = [
    HEADER,
    "",
    "# Content kinds",
    "",
    "The kinds of content the core and the modules define. An entry is a `.tres` resource of its kind's class, which extends `ContentEntry`, and its game lists it in a content pack (`game/data/content.tres`); `node tools/new_content.js --game <id> --kind <kind> --id <id>` writes one and lists it. Besides the fields below, every entry has its `id` (a `StringName` that never changes once it ships) and `custom_fields` (JSON-safe data a game or mod attaches). A game has the core's kinds and those of the modules it links. Each entry's `find_problems()` checks its fields and the ids they name against the game's content, and a problem fails validation. An enum field is written as its number.",
    "",
    "| Kind | Layer | Class | Script |",
    "| --- | --- | --- | --- |",
  ];
  for (const entry of kinds) lines.push(`| [${entry.kind}](#${entry.kind}) | ${entry.layer} | \`${entry.name}\` | \`${entry.file}\` |`);
  lines.push("");
  for (const entry of kinds) {
    const own = enumsByClass.get(entry.name);
    const summary = classSummary(entry.source);
    lines.push(`## ${entry.kind}`, "", `\`${entry.name}\` (${entry.layer}).${summary ? ` ${summary}` : ""}`, "");
    const fields = fieldsOf(entry.source);
    if (fields.length === 0) {
      lines.push("No fields besides `id` and `custom_fields`.", "");
      continue;
    }
    lines.push("| Field | Type | Default | What it is |", "| --- | --- | --- | --- |");
    for (const field of fields) {
      let type = field.type || (field.annotation === "_multiline" || field.annotation === "_file" || field.annotation === "_dir" ? "String" : typeOfDefault(field.initial));
      // A constant of the class's own enum or of an engine type (`Color.WHITE`).
      const constant = /^(\w+)\.[A-Z][A-Z0-9_]*$/.exec(field.initial);
      if (!type && constant && (own.has(constant[1]) || ENGINE_TYPE_RE.test(constant[1]))) type = constant[1];
      const hint = editorHint(field);
      const values = enumValues(type, own, enumsByClass);
      const meaning = [field.doc, values ? `Values: ${values}.` : ""].filter(Boolean).join(" ");
      lines.push(`| \`${field.name}\` | ${type ? `\`${cell(type)}\`` : ""}${hint ? `, ${cell(hint)}` : ""} | ${field.initial ? `\`${cell(field.initial)}\`` : ""} | ${cell(meaning)} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

function pages(foundation = readFoundation()) {
  return {
    "autoloads.md": autoloadsPage(foundation),
    "events.md": eventsPage(foundation),
    "rules.md": rulesPage(),
    "content.md": contentPage(),
  };
}

// The reference pages that differ from what the code gives.
function stalePages() {
  return Object.entries(pages())
    .filter(([name, text]) => {
      const file = path.join(REFERENCE_DIR, name);
      return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text;
    })
    .map(([name]) => `docs/reference/${name}`);
}

function writePages() {
  fs.mkdirSync(REFERENCE_DIR, { recursive: true });
  for (const [name, text] of Object.entries(pages())) fs.writeFileSync(path.join(REFERENCE_DIR, name), text, "utf8");
}

module.exports = { callArguments, classSummary, contentKinds, enumsOf, fieldsOf, pages, ruleKeys, signalsOf, stalePages };

if (require.main === module) {
  main(() => {
    const { values } = parseToolArgs({ options: { check: { type: "boolean", default: false } } });
    if (values.check) {
      const stale = stalePages();
      if (stale.length > 0) fail(`${stale.join(", ")} no longer match the code. Run: node tools/generate_reference.js`);
      console.log("Reference pages match the code.");
      return;
    }
    writePages();
    console.log("Wrote docs/reference/autoloads.md, events.md, rules.md and content.md.");
  });
}
